const existing = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {};
const result = { ...existing };
const fails = [];

for (const [id, short, full, city] of HOSPITALS) {
  if (result[id]?.lat) continue; // 已 geocode 過的跳過
  const q = encodeURIComponent(`${full} ${city}`);
  const url = `https://nominatim.openstreetmap.org/search?q=${q}&format=json&limit=1&countrycodes=tw`;
  try {
    const res = await fetch(url, { headers: { 'User-Agent': 'er-map-taiwan/1.0 (contact: local build)' } });
    const hits = await res.json();
    const h = hits[0];
    if (h) {
      const lat = parseFloat(h.lat), lng = parseFloat(h.lon);
      if (lat > 21.9 && lat < 25.3 && lng > 119.3 && lng < 122.1) {
        result[id] = { short, full: DISPLAY[id] || full, city, lat, lng };
        console.log(`OK  ${short} -> ${lat.toFixed(5)},${lng.toFixed(5)}  ${h.display_name.slice(0, 60)}`);
      } else {
        fails.push([id, short, `bounds fail: ${lat},${lng}`]);
      }
    } else {
      fails.push([id, short, 'no result']);
    }
  } catch (e) {
    fails.push([id, short, e.message]);
  }
  await sleep(1100); // Nominatim 1 req/s
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(result, null, 2));
console.log(`\n${Object.keys(result).length} geocoded, ${fails.length} failed`);
fails.forEach(([id, s, why]) => console.log(`FAIL ${id} ${s}: ${why}`));
